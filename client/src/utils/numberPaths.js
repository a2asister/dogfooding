export function interpolatePaths(pathA, pathB, progress) {
  const numsA = parsePath(pathA);
  const numsB = parsePath(pathB);
  
  if (numsA.length !== numsB.length) {
    return progress > 0.5 ? pathB : pathA;
  }
  
  const interpolated = numsA.map((num, i) => {
    return num + (numsB[i] - num) * progress;
  });
  
  return reconstructPath(pathA, interpolated);
}

function parsePath(path) {
  const nums = [];
  const regex = /[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?/g;
  let match;
  while ((match = regex.exec(path)) !== null) {
    nums.push(parseFloat(match[0]));
  }
  return nums;
}

function reconstructPath(template, values) {
  let result = template;
  const regex = /[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?/g;
  let i = 0;
  return result.replace(regex, () => {
    const val = values[i++];
    return Math.round(val * 100) / 100;
  });
}
